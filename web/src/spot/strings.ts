export const STRINGS: Record<Lang, Strings> = { en, ca, es }

const KEY = 'surf:lang'
const listeners = new Set<(l: Lang) => void>()
const isLang = (v: unknown): v is Lang => v === 'en' || v === 'ca' || v === 'es'

function readLang(): Lang {
  try {
    const v = localStorage.getItem(KEY)
    if (isLang(v)) return v
  } catch {
    /* private mode */
  }
  const nav = navigator.language?.toLowerCase() ?? ''
  return nav.startsWith('ca') ? 'ca' : nav.startsWith('es') ? 'es' : 'en'
}

/** The page language, shared by every component (changing it anywhere updates all of them). */
export function useLang(): [Lang, Strings, (l: Lang) => void] {
  const [lang, setLang] = useState<Lang>(readLang)
  useEffect(() => {
    listeners.add(setLang)
    document.documentElement.lang = lang
    return () => void listeners.delete(setLang)
  }, [lang])
  const set = (l: Lang) => {
    try {
      localStorage.setItem(KEY, l)
    } catch {
      /* can't save: the choice lasts until the page is closed */
    }
    listeners.forEach((f) => f(l))
  }
  return [lang, STRINGS[lang], set]
}

/** Short weekday in the page language ("Fri" / "dv." / "vie"). */
export const weekdayIn = (t: Strings, unix: number, tz: string) => new Intl.DateTimeFormat(t.locale, { weekday: 'short', timeZone: tz }).format(unix * 1000)

/** Local wind name for a direction the wind comes FROM. */
export const windName = (deg: number) => WIND_NAMES[Math.round((((deg % 360) + 360) % 360) / 45) % 8]
